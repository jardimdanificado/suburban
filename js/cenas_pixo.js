// Cenas de rua, muro e pixação.
//
// O gerador de pichações usa os temas normais, mas o repertório urbano era
// pequeno: muro, tinta e laje quase não apareciam. Estas cenas acrescentam
// vocabulário de rua sem inventar palavra nem quebrar a concordância. Elas
// entram no banco comum, então valem para qualquer texto temático.
//
// A forma é a mesma de js/gerador_textos.js: sujeito, verbo no infinitivo,
// objeto direto com artigo e gênero, e complemento opcional.
const C = (s, v, o, g, c = '') => {
  if (!o) return { s, v, o: null, c };
  const corte = o.indexOf(' ');
  return { s, v, o: { d: o.slice(0, corte), n: o.slice(corte + 1), g }, c };
};

