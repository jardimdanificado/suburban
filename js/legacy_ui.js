// Pre-rendered 16x16 glyph atlas cache per color (eliminates 10,000s of fillRect per frame)
const _glyphAtlasCache = new Map();

function getGlyphAtlas(color) {
  let atlas = _glyphAtlasCache.get(color);
  if (atlas) return atlas;

  atlas = document.createElement("canvas");
  atlas.width = 128;
  atlas.height = 128;
  const actx = atlas.getContext("2d");
  actx.fillStyle = color;

  for (let idx = 0; idx < 256; idx++) {
    const glyph = FONT_8X8[idx];
    if (!glyph) continue;
    const gx = (idx % 16) * 8;
    const gy = Math.floor(idx / 16) * 8;
    for (let r = 0; r < 8; r++) {
      const rowBits = glyph[r];
      let startC = -1;
      for (let c = 0; c < 8; c++) {
        if (rowBits & (1 << (7 - c))) {
          if (startC === -1) startC = c;
        } else {
          if (startC !== -1) {
            actx.fillRect(gx + startC, gy + r, c - startC, 1);
            startC = -1;
          }
        }
      }
      if (startC !== -1) {
        actx.fillRect(gx + startC, gy + r, 8 - startC, 1);
      }
    }
  }

  _glyphAtlasCache.set(color, atlas);
  return atlas;
}

/**
 * Draws crisp text using high-performance GPU-accelerated glyph atlas.
 */
export function drawText8x8(text, startX, startY, color = "#ffffff", scale = 1) {
  if (text === undefined || text === null) return;
  const str = String(text);
  const atlas = getGlyphAtlas(color);
  const dw = 8 * scale;
  const dh = 8 * scale;

  let cx = startX;
  let cy = startY;

  for (let i = 0; i < str.length; i++) {
    if (str[i] === "\n") {
      cx = startX;
      cy += 9 * scale;
      continue;
    }

    const codePoint = str.codePointAt(i);
    if (codePoint > 0xffff) {
      i++; // Account for surrogate pairs in JS string
    }

    const charIdx = mapUnicodeToGlyphIndex(codePoint);
    const gx = (charIdx % 16) * 8;
    const gy = Math.floor(charIdx / 16) * 8;

    ctx.drawImage(atlas, gx, gy, 8, 8, cx, cy, dw, dh);
    cx += dw;
  }
}

function wrapText8x8(text, maxCharsPerLine) {
  if (!text) return [];
  const words = text.split(" ");
  const lines = [];
  let currentLine = "";

  for (let i = 0; i < words.length; i++) {
    const word = words[i];
    const testLine = currentLine ? `${currentLine} ${word}` : word;
    if (testLine.length > maxCharsPerLine && currentLine) {
      lines.push(currentLine);
      currentLine = word;
    } else {
      currentLine = testLine;
    }
  }
  if (currentLine) lines.push(currentLine);
  return lines;
}

export function drawText8x8Centered(text, startY, color = "#ffffff", scale = 1, shadowColor = "#000000", shadowOffset = 2, customWidth = null) {
  if (text === undefined || text === null) return;
  const str = String(text);
  const textWidth = str.length * 8 * scale;
  const totalW = customWidth || CANVAS_WIDTH;
  const startX = Math.floor((totalW - textWidth) / 2);
  if (shadowColor) {
    drawText8x8(str, startX + shadowOffset, startY + shadowOffset, shadowColor, scale);
  }
  drawText8x8(str, startX, startY, color, scale);
}
export function drawNESBox(x, y, w, h) {
  ctx.save();
  ctx.fillStyle = "#000000";
  ctx.fillRect(x, y, w, h);

  ctx.strokeStyle = "#ffffff";
  ctx.lineWidth = 2;
  ctx.strokeRect(x + 1, y + 1, w - 2, h - 2);
  ctx.restore();
}

export function drawNESButton(x, y, w, h, text, isSelected = false, isDanger = false) {
  const isHover = mouseX >= x && mouseX <= x + w && mouseY >= y && mouseY <= y + h;

  ctx.save();
  ctx.fillStyle = isDanger ? (isHover ? "#880000" : "#000000") : (isHover ? "#222222" : "#000000");
  ctx.fillRect(x, y, w, h);

  ctx.strokeStyle = isSelected ? "#f8b800" : (isHover ? "#ffffff" : (isDanger ? "#e40058" : "#7c7c7c"));
  ctx.lineWidth = 2;
  ctx.strokeRect(x + 1, y + 1, w - 2, h - 2);

  const textCol = isDanger ? "#ff6060" : (isSelected || isHover ? "#f8b800" : "#ffffff");
  const prefix = isSelected || isHover ? "▶" : "";
  const fullText = `${prefix}${text}`;
  const textWidth = fullText.length * 8;
  const tx = Math.floor(x + (w - textWidth) / 2);
  const ty = Math.floor(y + (h - 8) / 2);

  drawText8x8(fullText, tx, ty, textCol, 1);
  ctx.restore();
}

export function drawNESProgressBar(x, y, w, h, val, max, label, color = "#58d854") {
  const pct = Math.max(0, Math.min(1, max > 0 ? val / max : 0));
  ctx.save();

  ctx.fillStyle = "#000000";
  ctx.fillRect(x, y, w, h);

  ctx.strokeStyle = "#ffffff";
  ctx.lineWidth = 2;
  ctx.strokeRect(x + 1, y + 1, w - 2, h - 2);

  if (pct > 0) {
    ctx.fillStyle = color;
    ctx.fillRect(x + 3, y + 3, (w - 6) * pct, h - 6);
  }

  // Label in 8x8 font
  drawText8x8(label, x + 6, y + Math.floor((h - 8) / 2), "#ffffff", 1);

  const valStr = `${Math.round(val)}/${Math.round(max)}`;
  const valWidth = valStr.length * 8;
  drawText8x8(valStr, x + w - valWidth - 6, y + Math.floor((h - 8) / 2), "#f8b800", 1);

  ctx.restore();
}

/** Canvas UI primitives ported from Brutopolis' original NES-style UI. */
export class LegacyCanvasUI {
  constructor(canvas) {
    this.canvas = canvas;
    this.ctx = canvas.getContext("2d");
    this.width = 800;
    this.height = 600;
    this.dpr = 1;
    this.regions = [];
    this.resize();
  }

  resize() {
    this.width = this.canvas.clientWidth || window.innerWidth;
    this.height = this.canvas.clientHeight || window.innerHeight;
    this.dpr = Math.min(window.devicePixelRatio || 1, 2);
    const w = Math.round(this.width * this.dpr);
    const h = Math.round(this.height * this.dpr);
    if (this.canvas.width !== w || this.canvas.height !== h) {
      this.canvas.width = w;
      this.canvas.height = h;
    }
    CANVAS_WIDTH = this.width;
    CANVAS_HEIGHT = this.height;
    ctx = this.ctx;
    this.ctx.setTransform(this.dpr, 0, 0, this.dpr, 0, 0);
  }

  beginFrame(pointerX = -1, pointerY = -1) {
    this.resize();
    mouseX = pointerX;
    mouseY = pointerY;
    this.ctx.clearRect(0, 0, this.width, this.height);
    this.regions = [];
  }

  button(x, y, w, h, label, onClick, { selected = false, danger = false } = {}) {
    drawNESButton(x, y, w, h, label, selected, danger);
    this.regions.push({ x, y, w, h, onClick });
  }

  text(value, x, y, color = "#ffffff", scale = 1) {
    drawText8x8(value, x, y, color, scale);
  }

  box(x, y, w, h) { drawNESBox(x, y, w, h); }

  bar(x, y, w, h, value, max, label, color) {
    drawNESProgressBar(x, y, w, h, value, max, label, color);
  }

  /** Clip drawing AND pointer targets so scrolled controls cannot cover other panels. */
  clip(x, y, w, h, draw) {
    return clipCanvasRegion(this, x, y, w, h, draw);
  }

  panel(x, y, w, h, title, text) {
    this.regions.push({ x, y, w, h, onClick: null });
    drawNESBox(x, y, w, h);
    ctx.fillStyle = "#171717";
    ctx.fillRect(x + 3, y + 3, w - 6, 20);
    drawText8x8(title, x + 8, y + 9, "#f8b800", 1);
    const maxChars = Math.max(1, Math.floor((w - 16) / 8));
    const lines = wrapText8x8(String(text || ""), maxChars);
    const maxLines = Math.floor((h - 38) / 10);
    for (let i = 0; i < Math.min(lines.length, maxLines); i++) {
      drawText8x8(lines[i], x + 8, y + 32 + i * 10, "#ffffff", 1);
    }
  }

  drawHud({ title = "EXPERIENCE", status = "", buttons = [] } = {}) {
    drawNESBox(0, 0, this.width, 34);
    drawText8x8(title, 8, 13, "#f8b800", 1);
    if (status) drawText8x8(status, Math.min(this.width - status.length * 8 - 12, Math.max(92, title.length * 8 + 12)), 13, "#bcbcbc", 1);
    let x = Math.max(150, this.width - buttons.reduce((sum, b) => sum + Math.max(48, b.label.length * 8 + 18) + 6, 0) - 8);
    for (const item of buttons) {
      const w = Math.max(48, item.label.length * 8 + 18);
      this.button(x, 5, w, 24, item.label, item.onClick, { selected: !!item.selected });
      x += w + 6;
    }
  }

  drawActionBar(buttons = [], { timeControls = [] } = {}) {
    const widthFor = (item) => Math.max(32, item.label.length * 8 + 18);
    const total = [...buttons, ...timeControls].reduce((sum, item) => sum + widthFor(item) + 6, 10);
    const twoRows = timeControls.length > 0 && total > this.width - 8;
    const h = twoRows ? 68 : 36;
    const y = this.height - h;
    drawNESBox(0, y, this.width, h);
    const drawRow = (items, rowY, startX = 8) => {
      let x = startX;
      for (const item of items) {
        const w = widthFor(item);
        if (x + w > this.width - 8) break;
        this.button(x, rowY, w, 24, item.label, item.onClick, { selected: !!item.selected });
        x += w + 6;
      }
      return x;
    };
    const x = drawRow(buttons, y + 6);
    drawRow(timeControls, twoRows ? y + 36 : y + 6, twoRows ? 8 : x + 8);
  }

  clickAt(x, y) {
    const region = this.hitTest(x, y);
    if (region) region.onClick?.();
    return !!region;
  }

  hitTest(x, y) {
    return [...this.regions].reverse().find((r) => x >= r.x && x <= r.x + r.w && y >= r.y && y <= r.y + r.h) || null;
  }
}

